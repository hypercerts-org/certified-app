/** Unpack the hex string into one byte per cell. */
export function unpackLandMask(): Uint8Array {
  const { cols, rows, hex } = LAND_MASK
  const out = new Uint8Array(cols * rows)
  for (let i = 0; i < out.length; i++) {
    const nibble = Number.parseInt(hex[i >> 2], 16)
    out[i] = (nibble >> (3 - (i & 3))) & 1
  }
  return out
}
